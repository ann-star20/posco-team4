# ------------------------------------------------------------------ 문서 도구
class Doc:
    def __init__(self, title, subtitle, meta):
        self.d = Document()
        st = self.d.styles["Normal"]
        st.font.name, st.font.size = FONT, Pt(10.5)
        st.element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
        st.paragraph_format.line_spacing = 1.5
        st.paragraph_format.space_after = Pt(6)
        for s in self.d.sections:
            s.left_margin = s.right_margin = Cm(2.3)
            s.top_margin = s.bottom_margin = Cm(2.3)
        for nm, sz in (("Heading 1", 15), ("Heading 2", 12.5), ("Heading 3", 11)):
            h = self.d.styles[nm]
            h.font.name, h.font.size, h.font.bold = FONT, Pt(sz), True
            h.font.color.rgb = RGBColor(0x1F, 0x3A, 0x5F)
            h.element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
            h.paragraph_format.space_before = Pt(14 if nm == "Heading 1" else 10)
        self.nfig = self.ntab = 0
        for _ in range(5):
            self.d.add_paragraph()
        t = self.d.add_paragraph()
        t.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = t.add_run(title)
        r.bold, r.font.size = True, Pt(22)
        t = self.d.add_paragraph()
        t.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = t.add_run(subtitle)
        r.font.size = Pt(13)
        for _ in range(3):
            self.d.add_paragraph()
        for m in meta:
            p = self.d.add_paragraph()
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            p.add_run(m).font.size = Pt(10.5)
        self.d.add_page_break()
        self.footer()

    def footer(self):
        p = self.d.sections[0].footer.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run()
        for typ, txt in (("begin", None), (None, "PAGE"), ("end", None)):
            if typ:
                e = OxmlElement("w:fldChar")
                e.set(qn("w:fldCharType"), typ)
            else:
                e = OxmlElement("w:instrText")
                e.set(qn("xml:space"), "preserve")
                e.text = txt
            r._r.append(e)

    def h(self, text, lvl=1):
        self.d.add_heading(text, lvl)

    def p(self, text):
        para = self.d.add_paragraph()
        para.paragraph_format.first_line_indent = Cm(0.6)
        self._runs(para, text)

    def b(self, items):
        for it in items:
            self._runs(self.d.add_paragraph(style="List Bullet"), it)

    def _runs(self, para, text):
        import re
        for t in re.split(r"(\*\*[^*]+\*\*)", text):
            if t.startswith("**"):
                para.add_run(t[2:-2]).bold = True
            elif t:
                para.add_run(t)

    def table(self, caption, header, rows, widths=None):
        self.ntab += 1
        c = self.d.add_paragraph()
        c.paragraph_format.keep_with_next = True
        c.add_run(f"표 {self.ntab}. {caption}").bold = True
        t = self.d.add_table(rows=1 + len(rows), cols=len(header))
        t.style = "Table Grid"
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        for j, v in enumerate(header):
            cell = t.cell(0, j)
            cell.text = ""
            r = cell.paragraphs[0].add_run(str(v))
            r.bold, r.font.size = True, Pt(9)
            sh = OxmlElement("w:shd")
            sh.set(qn("w:val"), "clear")
            sh.set(qn("w:fill"), "DCE6F1")
            cell._tc.get_or_add_tcPr().append(sh)
        for i, row in enumerate(rows, 1):
            for j, v in enumerate(row):
                cell = t.cell(i, j)
                cell.text = ""
                cell.paragraphs[0].add_run(str(v)).font.size = Pt(9)
        for row in t.rows:
            for cell in row.cells:
                for para in cell.paragraphs:
                    para.paragraph_format.line_spacing = 1.15
                    para.paragraph_format.space_after = Pt(2)
        self.d.add_paragraph()

    def fig(self, path, caption, width=16):
        self.nfig += 1
        self.d.add_picture(str(path), width=Cm(width))
        self.d.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
        c = self.d.add_paragraph()
        c.alignment = WD_ALIGN_PARAGRAPH.CENTER
        c.add_run(f"그림 {self.nfig}. {caption}").italic = True

    def save(self, path):
        self.d.save(path)
        print("저장:", path)


def pct(x, d=0):
    return f"{100 * x:.{d}f} %"


