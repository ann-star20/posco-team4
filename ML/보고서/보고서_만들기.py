    ax.axhline(1, color="r", ls="--", lw=0.8)
    ax.set_xticks(range(4))
    ax.set_xticklabels(outs)
    ax.set_ylabel("노브 1 % 변화의 신호 / 가정 측정 잡음(1 σ)")
    ax.legend()
    ax.set_title("웨이퍼 1장 측정 기준. 1 이면 노브 1 % 변화가 잡음 1σ 와 같다", fontsize=9)
